# --- TocDocTemplate ----------------------------------------------------------
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))


def add_heading(text, style, level=0):
    """Cria Paragraph com bookmark para TOC."""
    key = 'h_' + hashlib.md5((text + str(level)).encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/>{text}', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


# --- Markdown -> Flowables ---------------------------------------------------
def md_to_flowables(md_text: str):
    """Converte o corpo Markdown de um artigo em lista de Flowables ReportLab."""
    flowables = []
    # Remove linhas que começam com emoji "👉" ou outras referências internas do Personare
    cleaned_lines = []
    for line in md_text.split('\n'):
        # Pula linhas que começam com emoji de link relacionado
        if line.lstrip().startswith('👉'):
            continue
        # Pula linhas com "Leia também", "Leia aqui", "Leia mais" no início (CTAs internos)
        if re.match(r'^\s*(Leia (também|aqui|mais):)', line):
            continue
        cleaned_lines.append(line)
    lines = cleaned_lines
    i = 0
    is_first_para = True
    while i < len(lines):
        line = lines[i].rstrip()
        # Pula linhas vazias
        if not line.strip():
            i += 1
            continue
        # Pula o título h1 (já foi renderizado como article_title)
        if line.startswith('# ') and i < 3:
            i += 1
            continue
        # Subtítulo em itálico logo abaixo do h1
        if line.startswith('*') and line.endswith('*') and i < 5:
            subtitle = line.strip('*').strip()
            if subtitle:
                flowables.append(Paragraph(subtitle, styles['article_subtitle']))
                flowables.append(Spacer(1, 2))
            i += 1
            continue
        # h2
        if line.startswith('## '):
            text = line[3:].strip()
            flowables.append(Paragraph(text, styles['h2']))
            i += 1
            continue
        # h3
        if line.startswith('### '):
            text = line[4:].strip()
            flowables.append(Paragraph(text, styles['h3']))
            i += 1
            continue
        # h4+
        if line.startswith('#'):
            text = line.lstrip('#').strip()
            flowables.append(Paragraph(text, styles['h3']))
            i += 1
            continue
        # blockquote
        if line.startswith('> '):
            text = line[2:].strip()
            flowables.append(Paragraph(text, styles['closing']))
            i += 1
            continue
        # list item
        if line.startswith('- ') or re.match(r'^\d+\. ', line):
            is_ordered = bool(re.match(r'^\d+\. ', line))
            if is_ordered:
                text = re.sub(r'^\d+\. ', '', line).strip()
            else:
                text = line[2:].strip()
            # Sanitize asteriscos Markdown
            text = text.replace('**', '').replace('*', '')
            bullet = '•' if not is_ordered else '·'
            flowables.append(Paragraph(f'{bullet}  {text}', styles['list_item']))
            i += 1
            continue
        # parágrafo normal: junta com próximas linhas até encontrar linha vazia ou heading
        para_lines = [line]
        j = i + 1
        while j < len(lines):
            nl = lines[j].rstrip()
            if not nl.strip():
                break
            if nl.startswith(('#', '- ', '> ')) or re.match(r'^\d+\. ', nl):
                break
            para_lines.append(nl)
            j += 1
        para_text = ' '.join(para_lines).strip()
        # Limpa marcações Markdown
        para_text = para_text.replace('**', '').replace('*', '')
        # Escapa &, <, > (mas preserva tags <super>, <sub>, <b>, <i>)
        para_text = (para_text
                     .replace('&', '&')
                     .replace('<', '<')
                     .replace('>', '>')
                     )
        if para_text:
            style_key = 'body_first' if is_first_para else 'body'
            flowables.append(Paragraph(para_text, styles[style_key]))
            is_first_para = False
        i = j
    return flowables


