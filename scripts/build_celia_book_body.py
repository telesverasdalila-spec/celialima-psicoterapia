def format_date(date_str: str) -> str:
    """ISO -> 'dd/mm/aaaa' (ou só ano se falhar)."""
    if not date_str:
        return ''
    try:
        d = date_str[:10]
        y, m, day = d.split('-')
        return f"{day}/{m}/{y}"
    except Exception:
        return date_str[:10] if len(date_str) >= 10 else date_str


